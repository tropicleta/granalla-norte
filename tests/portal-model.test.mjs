import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import vm from 'node:vm';
import ts from 'typescript';
const require = createRequire(import.meta.url);
const exports = {};
class ContentError extends Error { constructor(message, status = 400) { super(message); this.status = status; } }
const code = ts.transpileModule(readFileSync(new URL('../src/lib/portal.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
vm.runInNewContext(code, { exports, require: name => name === 'next/headers' ? {} : name === './content-storage' ? {} : name === './admin-session' ? { configuredPassword: () => 'private-test-secret-1234567890' } : name === './content-model' ? { ContentError } : require(name), Buffer, Date, TextEncoder, TextDecoder, Uint8Array });
const hash = await exports.hashPassword('long-password-12345');
assert.notEqual(hash, await exports.hashPassword('long-password-12345'));
assert.ok(await exports.checkPassword('long-password-12345', hash));
assert.equal(await exports.checkPassword('wrong', hash), false);
assert.equal(await exports.checkPassword('anything'), false);
const client = { id: 'client-a', name: 'A', email: 'a@example.com', active: true, passwordHash: hash, sessionVersion: 'v1', projects: [] };
const token = exports.issueToken(client);
assert.equal(exports.verifyToken(token, [client]), client);
assert.equal(exports.verifyToken(token + 'x', [client]), null);
assert.equal(exports.verifyToken(token + '.', [client]), null);
assert.equal(exports.verifyToken(token, [{ ...client, active: false }]), null);
assert.equal(exports.verifyToken(token, [{ ...client, sessionVersion: 'v2' }]), null);
assert.equal(exports.verifyToken(token, [{ ...client, passwordHash: await exports.hashPassword('new-password-12345') }]), null);
assert.equal(exports.verifyToken(token, [{ ...client, id: 'client-b' }]), null);
const project = exports.projectInput({ name: 'Obra', status: 'En ejecución', partCount: 2, partNames: ['Etapa 1', 'Etapa 2'] });
assert.equal(project.parts.length, 2);
assert.equal(project.parts[1].name, 'Etapa 2');
project.parts[1].documents.push({ id: 'doc', path: 'private/path', name: 'Informe', filename: 'informe.pdf', size: 20, uploadedAt: new Date().toISOString() });
assert.throws(() => exports.projectInput({ name: 'Obra', status: 'Finalizado', partCount: 1 }, project), /documentos/);
const edited = exports.projectInput({ name: 'Obra editada', status: 'Finalizado', partCount: 3 }, project);
assert.equal(edited.id, project.id); assert.equal(edited.parts[1].id, project.parts[1].id); assert.equal(edited.parts[1].documents.length, 1);
client.projects.push(edited);
const safe = exports.publicClient(client);
assert.ok(!('passwordHash' in safe)); assert.ok(!('sessionVersion' in safe)); assert.ok(!('path' in safe.projects[0].parts[1].documents[0]));
assert.throws(() => exports.projectInput({ name: 'Obra', status: 'En ejecución', partCount: 101 }));
assert.throws(() => exports.projectInput({ name: 'Obra', status: 'invalid', partCount: 1 }));
assert.throws(() => exports.projectInput({ name: 'Obra', status: 'En ejecución', partCount: 1, description: 'x'.repeat(2001) }), /2000/);
assert.throws(() => exports.projectInput({ name: 'Obra', status: 'En ejecución', partCount: 1, description: {} }), /descripción/);
assert.throws(() => exports.password('short'));
assert.throws(() => exports.email('invalid'));
assert.equal(exports.email(' A@Example.com '), 'a@example.com');
console.log('Portal model checks passed: salted passwords, session integrity and invalidation, safe serialization, parts, retained documents and validation.');
